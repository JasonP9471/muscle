test('onboarding through completed workout, recovery, history, progress, persistence, and export', async ({ page }) => {
  test.slow()
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Train smarter/ })).toBeVisible()
  await page.getByRole('button', { name: /Build my training plan/ }).click()

  await page.getByLabel('Name').fill('Jason')
  await page.getByRole('button', { name: /Continue/ }).click()
  await page.getByRole('button', { name: 'Intermediate' }).click()
  await page.getByRole('button', { name: 'Get Stronger' }).click()
  await page.getByRole('button', { name: /Continue/ }).click()
  await page.getByRole('button', { name: 'Push / Pull / Legs', exact: true }).click()
  await page.getByRole('button', { name: '45' }).last().click()
  await page.getByRole('button', { name: /Continue/ }).click()
  await page.getByRole('button', { name: /Continue/ }).click()
  await page.getByRole('button', { name: /Continue/ }).click()
  await page.getByRole('button', { name: /Continue/ }).click()
  await page.getByRole('button', { name: /Create my TrainOS plan/ }).click()

  await expect(page.getByText('TrainOS Coach')).toBeVisible()
  await page.getByRole('link', { name: 'Train' }).click()
  await expect(page.getByText('Today’s workout', { exact: false }).first()).toBeVisible()
  await expect(page.getByText('Exercise library', { exact: true })).not.toBeVisible()
  await page.getByRole('button', { name: 'Workout options' }).click()
  const workoutOptions = page.getByRole('dialog', { name: 'Workout options' })
  await expect(workoutOptions).toBeVisible()
  await expect(workoutOptions.getByRole('button', { name: /Regenerate workout/ })).toBeVisible()
  await expect(workoutOptions.getByRole('button', { name: /Exercise library/ })).toBeVisible()
  await page.getByRole('button', { name: 'Close workout options' }).click()
  await expect(page.getByRole('heading', { name: /Push ·/ })).toBeVisible()
  const firstExerciseName = await page.locator('.editor-exercise h2').first().textContent()
  await page.getByRole('button', { name: /Replace exercise/ }).first().click()
  const substitutionDialog = page.getByRole('dialog', { name: 'Choose the best substitute' })
  await expect(substitutionDialog).toBeVisible()
  await page.locator('.picker-exercise').first().click()
  await expect(substitutionDialog).not.toBeVisible()
  await expect(page.locator('.editor-exercise h2').first()).not.toHaveText(firstExerciseName ?? '')

  await page.locator('.sticky-start').getByRole('button', { name: 'Start workout', exact: true }).click()
  await expect(page).toHaveURL(/\/workout\/active$/)
  await expect(page.getByText(/0 of \d+ sets/).first()).toBeVisible()
  await expect(page.locator('.active-exercise-card.current')).toHaveCount(1)
  await expect(page.locator('.active-exercise-card.inactive').first()).toBeVisible()
  const formGuide = page.locator('.active-guidance-quick').first()
  await expect(formGuide.getByRole('img')).toHaveAttribute('src', /\/exercise-guides\/library\/.+\.webp$/)
  await expect(formGuide.getByText('Setup', { exact: true })).toBeVisible()
  await expect(formGuide.getByText('Do this', { exact: true })).toBeVisible()
  await expect(formGuide.getByText('Avoid this', { exact: true })).toBeVisible()
  const firstSet = page.locator('.active-set-row').first()
  await firstSet.locator('input').nth(0).fill('95')
  await firstSet.locator('input').nth(1).fill('6')
  await firstSet.locator('.set-check').click()
  await expect(firstSet).not.toHaveClass(/current-set/)
  await expect(page.locator('.active-exercise-card.current .active-set-row.current-set')).toBeVisible()
  await expect(page.getByText('REST TIMER')).toBeVisible()

  await page.reload()
  await expect(page.getByText(/1 of \d+ sets/).first()).toBeVisible()
  await expect(page.locator('.active-set-row').first()).toHaveClass(/completed/)

  await page.getByRole('button', { name: 'Finish & save' }).click()
  await page.getByRole('button', { name: 'Finish & save' }).last().click()
  await expect(page.getByRole('heading', { name: 'Session logged.' })).toBeVisible()
  await page.getByRole('button', { name: 'good' }).click()
  await page.getByRole('button', { name: /Back to Today/ }).click()
  await expect(page.getByRole('heading', { name: 'Jason' })).toBeVisible()
  await expect(page.locator('.recovery-snapshot em').filter({ hasNotText: '100%' }).first()).toBeVisible()

  await page.getByRole('link', { name: 'Nutrition' }).click()
  await expect(page).toHaveURL(/\/nutrition$/)
  await page.getByRole('button', { name: /Log food/ }).first().click()
  await page.getByLabel('Search food database').fill('chicken')
  await page.locator('.food-result').filter({ hasText: 'Grilled chicken breast' }).click()
  await page.getByRole('button', { name: /^Add food/ }).click()
  await expect(page.getByText(/280 kcal/).first()).toBeVisible()

  await page.getByRole('link', { name: 'Progress' }).click()
  await expect(page).toHaveURL(/\/progress$/)
  await expect(page.getByText('Workouts this week').locator('..').getByText('1', { exact: true })).toBeVisible()
  await page.getByLabel(/Current weight/).fill('191')
  await page.getByRole('button', { name: /Log weight/ }).click()
  await page.goto('/history')
  await expect(page.locator('.history-card-full')).toHaveCount(1)

  await page.goto('/settings')
  await expect(page.getByLabel('Primary goal')).toHaveValue('get_stronger')
  await expect(page.getByLabel('Goal rate')).toHaveValue('moderate')
  await expect(page.getByLabel('Daily activity')).toHaveValue('moderate')
  await expect(page.getByLabel('Diet preference')).toHaveValue('high_protein')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: /Export all data/ }).click()
  expect((await download).suggestedFilename()).toMatch(/^trainos-backup-.*\.json$/)
})
