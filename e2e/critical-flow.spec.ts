import { expect, test } from '@playwright/test'

test('onboarding offers login and a default starter plan', async ({ page }) => {
  await page.goto('/onboarding')
  await page.evaluate(() => localStorage.setItem('trainos-local-only-v1', 'true'))

  await expect(page.getByRole('button', { name: /Already have an account\? Log in/ })).toBeVisible()
  await page.getByRole('button', { name: /Already have an account\? Log in/ }).click()
  await expect(page).toHaveURL(/\/auth$/)
  await expect.poll(() => page.evaluate(() => localStorage.getItem('trainos-local-only-v1'))).toBeNull()

  await page.goto('/onboarding')
  await page.getByRole('button', { name: 'Skip for now' }).click()
  await expect(page).toHaveURL(/\/today$/)
  await expect(page.getByText('TrainOS Coach')).toBeVisible()
})

test('onboarding validates name inline and keeps height and weight units aligned', async ({ page }) => {
  await page.goto('/onboarding')
  await page.getByRole('button', { name: /Build my training plan/ }).click()

  await expect(page.getByLabel('Height in feet')).toHaveValue('5')
  await expect(page.getByLabel('Height in inches')).toHaveValue('9')
  await expect(page.getByLabel(/Body weight/)).toHaveValue('165')
  await page.getByRole('button', { name: /Continue/ }).click()
  await expect(page.getByText('Enter your name to continue.')).toBeVisible()
  await expect(page.getByLabel(/Name/)).toHaveAttribute('aria-invalid', 'true')

  await page.getByRole('button', { name: 'Kg' }).click()
  await expect(page.getByLabel('Height in centimetres')).toHaveValue('175')
  await expect(page.getByLabel(/Body weight/)).toHaveValue('74.8')
})

test('an empty active workout exposes clear session controls and can switch plans', async ({ page }) => {
  await page.goto('/onboarding')
  await page.evaluate(() => localStorage.setItem('trainos-local-only-v1', 'true'))
  await page.getByRole('button', { name: 'Skip for now' }).click()
  await page.getByRole('link', { name: 'Train' }).click()
  await expect(page).toHaveURL(/\/train$/)
  await page.locator('.sticky-start').getByRole('button', { name: 'Start workout', exact: true }).click()

  await expect(page).toHaveURL(/\/workout\/active$/)
  await expect(page.getByText(/0 of \d+ sets/).first()).toBeVisible()
  await page.getByRole('button', { name: 'Session' }).click()
  await expect(page.getByRole('dialog', { name: 'What would you like to do?' })).toBeVisible()
  await expect(page.getByRole('button', { name: /Finish and save/ })).toBeDisabled()
  await expect(page.getByRole('button', { name: /Save and continue later/ })).toBeVisible()
  await expect(page.getByRole('button', { name: /End without saving/ })).toBeVisible()
  await page.getByRole('button', { name: /Switch workout/ }).click()
  await expect(page.getByRole('alertdialog', { name: 'Switch workouts?' })).toBeVisible()
  await page.getByRole('button', { name: 'End & switch' }).click()

  await expect(page).toHaveURL(/\/train$/)
  await expect(page.getByRole('heading', { name: /Full Body/ })).toBeVisible()
  await expect(page.getByText('Workout in progress')).not.toBeVisible()
})

test('an active workout can be paused and resumed from Today', async ({ page }) => {
  await page.goto('/onboarding')
  await page.evaluate(() => localStorage.setItem('trainos-local-only-v1', 'true'))
  await page.getByRole('button', { name: 'Skip for now' }).click()
  await page.getByRole('link', { name: 'Train' }).click()
  await expect(page).toHaveURL(/\/train$/)
  await page.locator('.sticky-start').getByRole('button', { name: 'Start workout', exact: true }).click()

  await expect(page).toHaveURL(/\/workout\/active$/)
  await page.getByRole('button', { name: 'Session' }).click()
  await page.getByRole('button', { name: /Save and continue later/ }).click()
  await expect(page).toHaveURL(/\/today$/)
  await expect(page.getByRole('button', { name: /Resume workout/ }).first()).toBeVisible()

  await page.getByRole('button', { name: /Resume workout/ }).first().click()
  await expect(page).toHaveURL(/\/workout\/active$/)
  await expect(page.getByText(/0 of \d+ sets/).first()).toBeVisible()
})

