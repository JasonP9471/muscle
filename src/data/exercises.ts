const createExercise = (seed: ExerciseSeed): Exercise => {
  const [name, movementPattern, primary, secondary, requiredEquipment, compound, unilateral = false, difficulty = 'beginner', exerciseType = 'weighted'] = seed
  return {
    id: slugify(name),
    name,
    aliases: aliases[name] ?? [],
    category: movementPattern === 'cardio' ? 'cardio' : primary,
    movementPattern,
    primaryMuscles: [{ muscle: primary, contribution: 1 }],
    secondaryMuscles: secondary.map((muscle, index) => ({ muscle, contribution: Math.max(0.25, 0.5 - index * 0.06) })),
    requiredEquipment,
    optionalEquipment: [],
    difficulty,
    exerciseType,
    instructions: patternInstructions[movementPattern],
    formTips: formTips[movementPattern],
    defaultRestSeconds: compound ? 120 : movementPattern === 'cardio' ? 30 : 75,
    compound,
    unilateral,
  }
}

export const EXERCISES: Exercise[] = seeds.map(createExercise)

export const EXERCISE_BY_ID = new Map(EXERCISES.map((exercise) => [exercise.id, exercise]))
